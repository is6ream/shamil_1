import type {
  CreatePaymentInput,
  CreatedPayment,
  ParsedWebhook,
  WebhookBody,
} from './payment-provider.types';

/**
 * Контракт платёжного провайдера.
 *
 * Модуль платежей написан вокруг этого интерфейса, а не вокруг одного SDK,
 * по двум причинам из CLAUDE.md: мерчант-аккаунты оформляются неделями и могут
 * не успеть к 5 октября, а набор провайдеров по странам разный — Robokassa
 * не закрывает ни Kaspi (KZ), ни Mbank (KG).
 *
 * Три метода — это три места, где поток касается внешнего мира. Всё остальное
 * (создание доната, идемпотентность, переход статуса, пересчёт витрин)
 * от провайдера не зависит и живёт в сервисе.
 */
export interface PaymentProvider {
  /** Код провайдера, он же `donation.provider`: 'manual' | 'robokassa' | … */
  readonly code: string;

  /**
   * Ссылка на оплату по заказу, который уже создал сервер.
   * Асинхронный намеренно: Robokassa ссылку подписывает локально, но Kaspi
   * и Mbank потребуют HTTP-вызова, и менять сигнатуру тогда придётся везде.
   */
  createPayment(input: CreatePaymentInput): Promise<CreatedPayment>;

  /**
   * Проверка подписи колбэка. Вызывается ДО разбора тела: не сошлось — 401
   * и ни одной записи в БД. Реализация обязана сравнивать подписи
   * регистронезависимо и за постоянное время.
   */
  verifySignature(body: WebhookBody): boolean;

  /**
   * Разбор проверенного колбэка. Бросает `WebhookParseError`, если тело
   * подписано верно, но не разбирается, — это не подделка, а расхождение
   * с документацией провайдера, и молчать о нём нельзя.
   */
  parseWebhook(body: WebhookBody): ParsedWebhook;
}

/** DI-токен: интерфейс в рантайме не существует, внедрять по нему нельзя. */
export const PAYMENT_PROVIDER = Symbol('PAYMENT_PROVIDER');
