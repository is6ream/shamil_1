-- Числовой номер счёта у доната.
--
-- Зачем он нужен: donation.id — это uuid, а Robokassa принимает InvId только
-- целым числом в диапазоне 0…2147483647 (int4). Отдавать провайдеру uuid
-- физически нельзя, а заводить свой счётчик в сервисе — значит получить гонку
-- на двух инстансах. Номер выдаёт последовательность PostgreSQL: она атомарна
-- и одинаково работает для всех трёх путей записи в donation (вебхук, ручной
-- донат из админки, сиды).
--
-- Публичный идентификатор заказа при этом остаётся uuid'ом: invoice_no уходит
-- только провайдеру и возвращается в колбэке, по нему донат маппится обратно.
-- Перебрать последовательный номер тривиально, uuid — нет.
--
-- SERIAL, а не собственная CREATE SEQUENCE: Prisma моделирует такую колонку как
-- autoincrement, и любое отклонение она считает дрейфом — следующая
-- `migrate dev` молча сгенерировала бы «исправляющую» миграцию боевой таблицы.
-- Нужные свойства SERIAL даёт сам: начиная с PostgreSQL 10 последовательность
-- создаётся AS integer, то есть с MAXVALUE 2147483647 и NO CYCLE. Второй круг
-- означал бы два доната с одним InvId — колбэк, применённый не к тому платежу;
-- вместо этого nextval упадёт ошибкой. Запас — 2,1 млрд платежей при 23 878
-- у референса за всё время сбора. Свойства проверяет schema-guards.spec.ts.
ALTER TABLE "donation" ADD COLUMN "invoice_no" SERIAL NOT NULL;

ALTER TABLE "donation"
  ADD CONSTRAINT "donation_invoice_no_positive" CHECK ("invoice_no" > 0);

-- Уникальность — не украшение: по этому номеру обработчик вебхука находит
-- донат. Два доната с одним номером = колбэк применяется к случайному из них.
CREATE UNIQUE INDEX "donation_invoice_no_key" ON "donation" ("invoice_no");

COMMENT ON COLUMN "donation"."invoice_no" IS
  'Числовой номер счёта для провайдера (Robokassa InvId, int4). Публичный id заказа — uuid';
COMMENT ON SEQUENCE "donation_invoice_no_seq" IS
  'Источник donation.invoice_no. AS integer: переполнение обязано падать, а не выдавать дубль';
