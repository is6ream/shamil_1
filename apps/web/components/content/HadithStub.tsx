interface Props {
  /** Что именно ждёт выверки: попадает в подпись рамки. */
  readonly label: string;
  /** Смысл по пересказу заказчика — не сам текст. */
  readonly gist?: string;
}

/**
 * Заглушка религиозного текста.
 *
 * Правило проекта: хадисы и аяты не публикуются без выверки заказчиком
 * или имамом — даже если горят сроки. Заказчик пересказывал их по памяти
 * и сам был не уверен в формулировках; придумывать или «восстанавливать»
 * текст хадиса нельзя.
 *
 * Видимая жёлтая рамка обязательна: она не даёт случайно отправить в прод
 * невыверенный текст. Убирать её должен тот же коммит, который подставляет
 * выверенную формулировку с источником.
 */
export function HadithStub({ label, gist }: Props) {
  return (
    <div className="stub">
      <div className="lbl">⟨заглушка⟩ {label}</div>
      <q>Здесь будет точная формулировка с источником</q>
      {gist === undefined ? null : <p className="gist">{gist}</p>}
    </div>
  );
}
