/**
 * Деградация серверного рендера, когда бэкенд недоступен.
 *
 * Главная не имеет права падать из-за витрины: форма пожертвования работает
 * и без цифр сбора (заказ создаётся из браузера отдельным запросом). Поэтому
 * страница просит данные через эту функцию и получает запасное значение:
 * `null` для цифр сбора (компоненты показывают «обновляем данные», а не «0 ₽»)
 * и пустые списки для рейтингов и ленты (пустой блок не рисуется вовсе).
 *
 * Ошибка не глотается молча: одна строка в серверный лог с именем блока.
 * ПДн в витринных ответах нет, так что в лог нечему утечь.
 */
export async function withFallback<T, F>(load: Promise<T>, fallback: F, what: string): Promise<T | F> {
  try {
    return await load;
  } catch (error: unknown) {
    const reason = error instanceof Error ? error.message : String(error);

    console.error(`[витрина] «${what}» недоступно, показываем запасной вариант: ${reason}`);

    return fallback;
  }
}
