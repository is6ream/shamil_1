const p = (text: string): LegalParagraph => ({ kind: "paragraph", text });

const term = (name: string, definition: string): LegalTerm => ({
  kind: "term",
  term: name,
  definition,
});

const bullets = (...items: string[]): LegalBullets => ({ kind: "bullets", items });

const clause = (number: string, ...content: LegalNode[]): LegalClause => ({
  kind: "clause",
  number,
  content,
});

const titledClause = (number: string, title: string, ...content: LegalNode[]): LegalClause => ({
  kind: "clause",
  number,
  title,
  content,
});

const section = (number: string, title: string, ...content: LegalNode[]): LegalSection => ({
  number,
  title,
  content,
});

function requisites(): LegalNode[] {
  const rows: ReadonlyArray<readonly [string, string | null]> = [
    ["Полное наименование", ORGANIZATION.legalName],
    ["ИНН", ORGANIZATION.inn],
    ["ОГРН/ОГРНИП", ORGANIZATION.ogrn],
    ["Контактный телефон", ORGANIZATION.phone],
    ["Контактный e-mail", ORGANIZATION.email],
  ];

  return rows
    .filter((row): row is readonly [string, string] => row[1] !== null)
    .map(([label, value]) => p(`${label}: ${value}`));
}

